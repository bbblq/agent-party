export const FURNITURE_CATALOG: readonly AssetCatalogEntry[] = (Object.keys(FURNITURE) as FurnitureKind[]).map((kind) => {
  const def = FURNITURE[kind];
  const meta = FURNITURE_META[kind];
  const passability: AssetPassability = def.seat ? 'seat' : def.blocks ? 'blocked' : 'walkable';
  const passabilityLabel = def.seat
    ? '座位（可寻路落座，不阻挡座位本身）'
    : def.blocks
      ? '阻挡通行（小人不可穿过）'
      : '可自由穿过';
  return {
    id: kind,
    kindKey: kind,
    section: 'furniture',
    category: meta.category,
    name: meta.name,
    mount: def.mount,
    footprint: { ...def.footprint },
    variants: [...(def.variants ?? [])],
    passability,
    passabilityLabel,
    interactive: meta.interactive,
    ...(meta.spotKind ? { spotKind: meta.spotKind } : {}),
    interactionDesc: meta.interactionDesc,
    rotatable: meta.rotatable,
    rotationDesc: meta.rotationDesc,
    ...(meta.tips ? { tips: meta.tips } : {}),
  };
});

